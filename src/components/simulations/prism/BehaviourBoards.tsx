"use client";
import type { ComponentType } from "react";
import { useState } from "react";
import { Actions, Choices, Stats, Slider, Ledger, fixed } from "./Shared";
export function Dissonance() {
  const [choice, setChoice] = useState(""),
    [strategy, setStrategy] = useState(""),
    [before, setBefore] = useState(3),
    [after, setAfter] = useState(3);
  return (
    <>
      <p>
        A fictional character values keeping an evening free but accepts
        optional overtime. Explore ways of responding to that conflict. Your
        discomfort ratings are self-reports, not values generated by a theory.
      </p>
      <Slider
        label="Initial reported discomfort (1–5)"
        min={1}
        max={5}
        value={before}
        onChange={setBefore}
      />
      <Choices
        label="Accept the scenario’s choice"
        options={["Keep overtime commitment", "Reconsider overtime"]}
        value={choice}
        onChange={(v) => {
          setChoice(v);
          setStrategy("");
        }}
      />
      {choice && (
        <>
          <Choices
            label="Explore a response"
            options={[
              "Change the behaviour",
              "Reassess the belief",
              "Add a justification",
              "Leave conflict unresolved",
            ]}
            value={strategy}
            onChange={setStrategy}
          />
          {strategy && (
            <>
              <p className="prism-panel">
                {strategy === "Change the behaviour"
                  ? "The character declines future optional overtime to align the action with the stated evening goal."
                  : strategy === "Reassess the belief"
                    ? "The character decides that the evening goal matters less than initially claimed."
                    : strategy === "Add a justification"
                      ? "The character treats this as an exceptional week with a specific financial purpose."
                      : "Both the stated priority and the conflicting action remain in view."}
              </p>
              <Slider
                label="Reported discomfort after considering response (1–5)"
                min={1}
                max={5}
                value={after}
                onChange={setAfter}
              />
              <Stats items={[["Your rating change", after - before]]} />
            </>
          )}
        </>
      )}
      <p>
        Cognitive dissonance concerns inconsistency and responses to it. The
        interface does not infer unconscious rationalisation, rank the responses
        ethically or force discomfort to fall.
      </p>
    </>
  );
}
export function Reactance() {
  const [before, setBefore] = useState(""),
    [message, setMessage] = useState(""),
    [after, setAfter] = useState("");
  return (
    <>
      <p>
        Two fictional café choices have identical prices. First record a
        preference; then consider a message about the choice. Both options
        remain available throughout.
      </p>
      <Choices
        label="Initial preference"
        options={["Tea", "Coffee"]}
        value={before}
        onChange={setBefore}
        disabled={!!message}
      />
      {before && (
        <Choices
          label="Message to inspect"
          options={["Neutral invitation", "Controlling instruction"]}
          value={message}
          onChange={(v) => {
            setMessage(v);
            setAfter("");
          }}
        />
      )}
      {message && (
        <>
          <p className="prism-panel">
            {message === "Neutral invitation"
              ? "You can choose tea or coffee; pick whichever suits you."
              : "You must pick tea. There is no acceptable reason to choose coffee."}
          </p>
          <Choices
            label="Preference after message"
            options={["Tea", "Coffee"]}
            value={after}
            onChange={setAfter}
          />
          <Stats
            items={[
              [
                "Recorded preference change",
                after
                  ? before === after
                    ? "Unchanged"
                    : `${before} → ${after}`
                  : "Awaiting response",
              ],
            ]}
          />
        </>
      )}
      <p>
        Psychological reactance concerns motivation to restore threatened
        freedom. A disclosed message and one preference report cannot diagnose
        it; switching, staying or rejecting the premise are all possible
        responses.
      </p>
    </>
  );
}
export function ChoiceOverload() {
  const [size, setSize] = useState("Twelve plans"),
    [chosen, setChosen] = useState<number | null>(null),
    all = Array.from({ length: 12 }, (_, i) => ({
      id: i,
      price: 8 + 2 * i,
      storage: 6 + 4 * (i % 4),
      flex: i % 3 === 0,
    })),
    plans =
      size === "Four plans"
        ? all.filter((p) => [0, 3, 6, 9].includes(p.id))
        : all;
  return (
    <>
      <p>
        Find the cheapest plan with at least 14 storage units and flexible
        cancellation, within a budget of 30. All offers are fictional; switching
        catalog size preserves the cheapest qualifying plan.
      </p>
      <Choices
        label="Catalog size"
        options={["Four plans", "Twelve plans"]}
        value={size}
        onChange={(v) => {
          setSize(v);
          setChosen(null);
        }}
      />
      <div className="prism-offers">
        {plans.map((p) => (
          <button
            key={p.id}
            aria-pressed={chosen === p.id}
            onClick={() => setChosen(p.id)}
          >
            Plan {"ABCDEFGHIJKL"[p.id]}
            <b>{p.price} units</b>
            <span>
              Storage {p.storage} · {p.flex ? "Flexible" : "Fixed term"}
            </span>
          </button>
        ))}
      </div>
      {chosen !== null && (
        <Stats
          items={[
            ["Selected plan", String.fromCharCode(65 + chosen)],
            [
              "Meets requirements",
              all[chosen].storage >= 14 && all[chosen].flex ? "Yes" : "No",
            ],
            ["Cheapest qualifying offer", "D · 14 units"],
          ]}
        />
      )}
      <p>
        Choice overload concerns conditions in which larger assortments hinder
        choice or satisfaction. This task records an actual selection; it does
        not impose slower responses or assume that more choice always hurts.
      </p>
    </>
  );
}
export function Negativity() {
  const [w, setW] = useState(1),
    [rating, setRating] = useState(7),
    [reveal, setReveal] = useState(false),
    weighted = (4 * 8 + 2 * w) / (4 + w);
  return (
    <>
      <p>
        A fictional review contains four positive ratings of 8 and one negative
        rating of 2 on a ten-point scale. Record your overall impression before
        inspecting an explicit weighting model.
      </p>
      <Slider
        label="Your overall impression (0–10)"
        min={0}
        max={10}
        value={rating}
        onChange={setRating}
        disabled={reveal}
      />
      <Actions>
        <button disabled={reveal} onClick={() => setReveal(true)}>
          Inspect feedback weighting
        </button>
      </Actions>
      {reveal && (
        <>
          <Slider
            label="Illustrative weight of the negative item"
            min={1}
            max={5}
            step={0.5}
            value={w}
            onChange={setW}
          />
          <Stats
            items={[
              ["Unweighted mean", 6.8],
              ["Chosen weighted mean", fixed(weighted)],
              ["Your recorded impression", rating],
            ]}
          />
        </>
      )}
      <p>
        Negativity bias concerns asymmetries in responses to negative and
        positive information. Your chosen weight is a teaching assumption, not
        an estimated psychological coefficient; unequal diagnostic relevance can
        also justify unequal weights.
      </p>
    </>
  );
}
export function Effort() {
  const [k, setK] = useState(1),
    [route, setRoute] = useState<string | null>(null),
    [steps, setSteps] = useState(0),
    need = route === "Long" ? 8 : 4,
    reward = route === "Long" ? 14 : 6;
  return (
    <>
      <p>
        Choose a delivery route: four steps for six tokens, or eight steps for
        fourteen. Inspect a transparent illustrative value rule V = reward − k ×
        effort, then complete a chosen route.
      </p>
      <Slider
        label="Illustrative cost per effort step k"
        min={0}
        max={3}
        step={0.25}
        value={k}
        onChange={setK}
        disabled={!!route}
      />
      <Ledger
        label="Supplied effort-value model"
        headers={["Route", "Steps", "Tokens", "Modelled net value"]}
        rows={[
          ["Short", 4, 6, fixed(6 - 4 * k)],
          ["Long", 8, 14, fixed(14 - 8 * k)],
        ]}
      />
      <Actions>
        {["Short", "Long"].map((r) => (
          <button key={r} disabled={!!route} onClick={() => setRoute(r)}>
            Choose {r.toLowerCase()} route
          </button>
        ))}
        {route && (
          <button disabled={steps === need} onClick={() => setSteps(steps + 1)}>
            Take next route step
          </button>
        )}
      </Actions>
      <Stats
        items={[
          ["Progress", route ? `${steps}/${need}` : "No route selected"],
          ["Tokens earned", route && steps === need ? reward : 0],
        ]}
      />
      <p>
        Effort discounting concerns how effort can reduce subjective value. The
        linear rule and clicking cost are authored examples, not a fitted
        utility function or a measure of motivation, fatigue or physical
        ability.
      </p>
    </>
  );
}

export default function GroupBoard({
  index,
  seed,
}: {
  index: number;
  seed: number;
}) {
  const B = [Dissonance, Reactance, ChoiceOverload, Negativity, Effort][
    index
  ] as ComponentType<{ seed: number }>;
  return <B seed={seed} />;
}
